"""Generates the static paths (ticks, coloured arcs) of the round instruments in ui/.

On the RP2040 a static path must never be redrawn because a hand moves, so no box of a static
path may overlap the box of a hand at any hand angle. The ticks are therefore grouped, and the
arcs cut, into paths whose boxes stay outside the reach of the hands. The script checks this for
every hand angle in steps of 0.1 degree.

Every coordinate is written as `size_float * A + B` with precomputed A and B, so each binding
depends on a single property: written with functions of `center`, `inner_radius` and so on,
the dependency nodes of the bindings cost about 16 KB more heap (measured with
tools/host-check).

Usage:
    python3 tools/dial-paths.py           # rewrite the generated paths in the .slint files
    python3 tools/dial-paths.py --check   # fail if a .slint file is not up to date

The generated part of a file lies between the BEGIN and END marker lines. Run the script again
after changing anything below, Theme.ring_ratio, Theme.marking_width or the hands.
"""

import math
import sys
from dataclasses import dataclass, field
from pathlib import Path

# the same values as in ui/theme.slint
RING_RATIO = 0.10  # Theme.ring_ratio
MARKING_WIDTH = 3.0  # Theme.marking_width in px

SIZE = 240  # instrument size used for the checks, the output scales with the size
CENTER = SIZE / 2
INNER_RADIUS = SIZE * (0.5 - RING_RATIO)

BEGIN = "    // BEGIN generated by tools/dial-paths.py, do not edit"
END = "    // END generated by tools/dial-paths.py"

TICK_CORNERS = [("inner", -1), ("outer", -1), ("outer", 1), ("inner", 1)]


@dataclass
class Tick:
    """a radial mark drawn as a thin filled quadrilateral"""

    angle: float  # degree, clockwise from 12 o'clock
    inner: float  # distances from the center, relative to the inner radius
    outer: float
    half_width: float  # px
    color: str


@dataclass
class Arc:
    """a coloured band along the dial"""

    start: float  # degree, clockwise from 12 o'clock
    end: float
    inner: float  # distances from the center, relative to the inner radius
    outer: float
    color: str
    name: str


@dataclass
class Hand:
    """a moving hand, the shape of the hands in the .slint files"""

    tip: float  # relative to the inner radius
    shoulder: float
    tail: float
    half_width: float  # px


@dataclass
class Dial:
    file: str
    min_distance: float  # smallest distance of a static box from the center, rel. inner radius
    hands: list
    ticks: list = field(default_factory=list)
    arcs: list = field(default_factory=list)
    # ticks drawn after the normal ticks (for example a red line), each in its own path
    marks: list = field(default_factory=list)
    # groups of ticks chosen by hand instead of the grouping by distance
    groups: list = None


def ratio(r):
    """distance relative to the inner radius -> relative to the instrument size"""
    return (0.5 - RING_RATIO) * r


def tick_coefficients(tick, corner, axis):
    """A and B of the coordinate `size_float * A + B` of a tick corner"""
    along, side = corner
    a = math.radians(tick.angle)
    r = ratio(tick.outer if along == "outer" else tick.inner)
    half_width = tick.half_width * side
    if axis == "x":
        return 0.5 + r * math.sin(a), half_width * math.cos(a)
    return 0.5 - r * math.cos(a), half_width * math.sin(a)


def arc_point(angle, r):
    """A of x and y of a point on an arc (B is 0)"""
    a = math.radians(angle)
    return 0.5 + ratio(r) * math.sin(a), 0.5 - ratio(r) * math.cos(a)


def tick_extremes(group):
    """(A, B) of the smallest and largest x and y of a group of ticks"""
    corners = [(t, c) for t in group for c in TICK_CORNERS]

    def value(e, axis):
        a, b = tick_coefficients(*e, axis)
        return a * SIZE + b

    x0 = min(corners, key=lambda e: value(e, "x"))
    x1 = max(corners, key=lambda e: value(e, "x"))
    y0 = min(corners, key=lambda e: value(e, "y"))
    y1 = max(corners, key=lambda e: value(e, "y"))
    return (
        tick_coefficients(*x0, "x"),
        tick_coefficients(*y0, "y"),
        tick_coefficients(*x1, "x"),
        tick_coefficients(*y1, "y"),
    )


def arc_extremes(arc, start, end):
    """(A, 0) of the smallest and largest x and y of a piece of an arc"""
    angles = [start, end] + [a for a in range(0, 721, 90) if start < a < end]
    points = [arc_point(a, r) for a in angles for r in (arc.inner, arc.outer)]
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return (min(xs), 0), (min(ys), 0), (max(xs), 0), (max(ys), 0)


def box(extremes):
    """box in px at SIZE, with the 1 unit margin of the viewbox"""
    (ax0, bx0), (ay0, by0), (ax1, bx1), (ay1, by1) = extremes
    return (
        ax0 * SIZE + bx0 - 1,
        ay0 * SIZE + by0 - 1,
        ax1 * SIZE + bx1 + 1,
        ay1 * SIZE + by1 + 1,
    )


def distance(b):
    """distance of the box from the center"""
    dx = max(b[0] - CENTER, 0, CENTER - b[2])
    dy = max(b[1] - CENTER, 0, CENTER - b[3])
    return math.hypot(dx, dy)


def group_ticks(ticks, min_distance):
    """fewest groups of neighbouring ticks whose boxes keep the distance"""
    best = None
    for start in range(len(ticks)):
        result, current = [], []
        for i in range(len(ticks)):
            index = (start + i) % len(ticks)
            candidate = [ticks[k] for k in current + [index]]
            if current and distance(box(tick_extremes(candidate))) < min_distance:
                result.append(current)
                current = [index]
            else:
                current.append(index)
        result.append(current)
        if best is None or len(result) < len(best):
            best = result
    return [[ticks[k] for k in g] for g in sorted(best, key=lambda g: g[0])]


def cut_arc(arc, min_distance):
    """fewest pieces whose boxes keep the distance

    A shorter piece has a smaller box, so making each piece as long as possible (in steps of
    0.25 degree) gives the fewest pieces. Near 12, 3, 6 and 9 o'clock pieces can be much longer
    than near the diagonals.
    """
    pieces = []
    start = arc.start
    while start < arc.end:
        end = start
        while end < arc.end and distance(box(arc_extremes(arc, start, min(end + 0.25, arc.end)))) >= min_distance:
            end = min(end + 0.25, arc.end)
        if end == start:
            sys.exit(f"{arc.name}: no cut found at {start} degree")
        pieces.append((start, end))
        start = end
    return pieces


def hand_box(hand, angle):
    s, c = math.sin(angle), math.cos(angle)
    points = [
        (-hand.tail, -hand.half_width),
        (hand.shoulder, -hand.half_width),
        (hand.tip, 0),
        (hand.shoulder, hand.half_width),
        (-hand.tail, hand.half_width),
    ]
    xs, ys = [], []
    for along, across in points:
        along = along * INNER_RADIUS if along != 0 else 0
        xs.append(CENTER + along * s + across * c)
        ys.append(CENTER - along * c + across * s)
    return min(xs) - 1, min(ys) - 1, max(xs) + 1, max(ys) + 1


def overlap(a, b):
    return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


def expression(a, b):
    # without a dependency on the size the property is a constant and needs no binding
    if abs(a) < 5e-7:
        return f"{b:.4f}"
    if abs(b) < 5e-5:
        return f"size_float * {a:.6f}"
    return f"size_float * {a:.6f} {'+' if b > 0 else '-'} {abs(b):.4f}"


def viewbox_lines(extremes):
    (ax0, bx0), (ay0, by0), (ax1, bx1), (ay1, by1) = extremes
    return [
        f"        viewbox-x: {expression(ax0, bx0 - 1)};",
        f"        viewbox-y: {expression(ay0, by0 - 1)};",
        f"        viewbox-width: {expression(ax1 - ax0, bx1 - bx0 + 2)};",
        f"        viewbox-height: {expression(ay1 - ay0, by1 - by0 + 2)};",
        "        x: self.viewbox-x * 1px;",
        "        y: self.viewbox-y * 1px;",
        "        width: self.viewbox-width * 1px;",
        "        height: self.viewbox-height * 1px;",
    ]


def tick_path(group):
    out = [f"    // {', '.join(f'{t.angle:g}deg' for t in group)}", "    Path {"]
    out += viewbox_lines(tick_extremes(group))
    out.append(f"        fill: {group[0].color};")
    for tick in group:
        for i, corner in enumerate(TICK_CORNERS):
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            out.append(f"            x: {expression(*tick_coefficients(tick, corner, 'x'))};")
            out.append(f"            y: {expression(*tick_coefficients(tick, corner, 'y'))};")
            out.append("        }")
        out.append("")
        out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def arc_path(arc, start, end):
    out = [f"    // {arc.name}, {start:g}deg to {end:g}deg", "    Path {"]
    out += viewbox_lines(arc_extremes(arc, start, end))
    out.append(f"        fill: {arc.color};")
    # outer edge clockwise, inner edge back
    steps = [
        ("MoveTo", start, arc.outer, None),
        ("ArcTo", end, arc.outer, "true"),
        ("LineTo", end, arc.inner, None),
        ("ArcTo", start, arc.inner, "false"),
    ]
    for element, angle, r, sweep in steps:
        x, y = arc_point(angle, r)
        out.append("")
        out.append(f"        {element} {{")
        out.append(f"            x: {expression(x, 0)};")
        out.append(f"            y: {expression(y, 0)};")
        if sweep:
            out.append(f"            radius-x: {expression(ratio(r), 0)};")
            out.append(f"            radius-y: {expression(ratio(r), 0)};")
            out.append(f"            sweep: {sweep};")
        out.append("        }")
    out.append("")
    out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def generate(dial):
    """the generated lines and a report, exits if a static box can be reached by a hand"""
    min_distance = dial.min_distance * INNER_RADIUS
    if dial.groups:
        tick_groups = dial.groups
    else:
        tick_groups = group_ticks(dial.ticks, min_distance) if dial.ticks else []
    arc_pieces = [(arc, s, e) for arc in dial.arcs for s, e in cut_arc(arc, min_distance)]

    boxes = [box(tick_extremes(g)) for g in tick_groups]
    boxes += [box(arc_extremes(*p)) for p in arc_pieces]
    boxes += [box(tick_extremes([m])) for m in dial.marks]
    for hand in dial.hands:
        for step in range(3600):
            hand_b = hand_box(hand, math.radians(step / 10))
            if any(overlap(hand_b, b) for b in boxes):
                sys.exit(f"{dial.file}: a hand overlaps a static box at {step / 10} degree")

    out = []
    for piece in arc_pieces:
        out += arc_path(*piece)
    for group in tick_groups:
        out += tick_path(group)
    for mark in dial.marks:
        out += tick_path([mark])
    report = (
        f"{dial.file}: {len(arc_pieces)} arc paths, {len(tick_groups)} tick paths "
        f"{[len(g) for g in tick_groups]}, {len(dial.marks)} marks, "
        + ("no overlap with the hands" if dial.hands else "no hands to check")
    )
    return out, report


def attitude():
    # bank ticks in the ring, from the outer edge (1.25 of the inner radius) to the inner edge
    # the moving inner disc has a fixed box, the hand-chosen groups keep the tick boxes away
    # from it, so there are no hands to check
    def tick(angle, width):
        return Tick(angle, 1.0, 1.25, width / 2, "Theme.marking")

    groups = [
        [tick(0, MARKING_WIDTH)],
        [tick(a, MARKING_WIDTH / 2) for a in (-20, -10, 10, 20)],
        [tick(a, MARKING_WIDTH) for a in (-60, -30)],
        [tick(a, MARKING_WIDTH) for a in (30, 60)],
    ]
    return Dial("ui/attitude.slint", 0, [], groups=groups)


def altimeter():
    # ticks every 20 ft, long and wide ones every 100 ft
    ticks = [
        Tick(
            k * 360 / 50,
            0.85 if k % 5 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if k % 5 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        for k in range(50)
    ]
    # 100 ft hand, the 1000 ft hand is shorter
    hands = [Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8)]
    return Dial("ui/altimeter.slint", 0.79, hands, ticks)


# airspeed scale: 0 to 40 kt on the first 30 degree, then 1.875 degree per kt
# (40 kt at 30 degree, 200 kt at 330 degree), like ui/airspeed.slint
def airspeed_angle(kt):
    return kt * 0.75 if kt < 40 else 30 + (kt - 40) * 1.875


# speed limits of a typical small trainer (Cessna 172), in kt
V_S0 = 40  # stall speed with flaps, start of the white arc
V_FE = 85  # highest speed with flaps, end of the white arc
V_S1 = 48  # stall speed clean, start of the green arc
V_NO = 129  # highest cruising speed, end of the green and start of the yellow arc
V_NE = 163  # never exceed, red line


def airspeed():
    # ticks every 5 kt from 40 to 200 kt, long and wide ones every 10 kt
    ticks = [
        Tick(
            airspeed_angle(kt),
            0.85 if kt % 10 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if kt % 10 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        for kt in range(40, 201, 5)
    ]
    # the arcs lie in the ring, inside the digits: white inside, green and yellow outside
    arcs = [
        Arc(airspeed_angle(V_S0), airspeed_angle(V_FE), 1.0, 1.04, "Theme.marking", "white arc"),
        Arc(airspeed_angle(V_S1), airspeed_angle(V_NO), 1.04, 1.10, "Theme.normal", "green arc"),
        Arc(airspeed_angle(V_NO), airspeed_angle(V_NE), 1.04, 1.10, "Theme.caution", "yellow arc"),
    ]
    marks = [Tick(airspeed_angle(V_NE), 0.92, 1.10, MARKING_WIDTH / 2, "Theme.limit")]
    hands = [Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8)]
    return Dial("ui/airspeed.slint", 0.79, hands, ticks, arcs, marks)


def main():
    check = "--check" in sys.argv[1:]
    root = Path(__file__).resolve().parent.parent
    outdated = []
    for dial in (attitude(), altimeter(), airspeed()):
        lines, report = generate(dial)
        print(report, file=sys.stderr)
        path = root / dial.file
        text = path.read_text()
        begin = text.index(BEGIN + "\n") + len(BEGIN) + 1
        end = text.index(END + "\n")
        new = text[:begin] + "\n".join(lines) + "\n" + text[end:]
        if new != text:
            if check:
                outdated.append(dial.file)
            else:
                path.write_text(new)
                print(f"{dial.file} updated", file=sys.stderr)
    if outdated:
        sys.exit(f"not up to date, run tools/dial-paths.py: {', '.join(outdated)}")


if __name__ == "__main__":
    main()
