"""Generates the static paths (ticks, coloured arcs) of the round instruments in ui/.

On the RP2040 a static path must never be redrawn because a hand moves, so no box of a static
path may overlap the box of a hand at any hand angle. The ticks are therefore grouped, and the
arcs cut, into paths whose boxes stay outside the reach of the hands. The script checks this for
every hand angle in steps of 0.1 degree.

Every coordinate is written as `size_float * A + B` with precomputed A and B, so each binding
depends on a single property: written with functions of `center`, `inner_radius` and so on,
the dependency nodes of the bindings cost about 16 KB more heap (measured with
tools/host-check).

Usage:
    python3 tools/dial-paths.py           # rewrite the generated paths in the .slint files
    python3 tools/dial-paths.py --check   # fail if a .slint file is not up to date

The generated part of a file lies between the BEGIN and END marker lines. Run the script again
after changing anything below, Theme.ring_ratio, Theme.marking_width or the hands.
"""

import math
import sys
from dataclasses import dataclass, field
from pathlib import Path

# the same values as in ui/theme.slint
RING_RATIO = 0.10  # Theme.ring_ratio
MARKING_WIDTH = 3.0  # Theme.marking_width in px

SIZE = 240  # instrument size used for the checks, the output scales with the size
CENTER = SIZE / 2
INNER_RADIUS = SIZE * (0.5 - RING_RATIO)

BEGIN = "    // BEGIN generated by tools/dial-paths.py, do not edit"
END = "    // END generated by tools/dial-paths.py"

TICK_CORNERS = [("inner", -1), ("outer", -1), ("outer", 1), ("inner", 1)]


@dataclass
class Tick:
    """a radial mark drawn as a thin filled quadrilateral"""

    angle: float  # degree, clockwise from 12 o'clock
    inner: float  # distances from the center, relative to the inner radius
    outer: float
    half_width: float  # px
    color: str


@dataclass
class Arc:
    """a coloured band along the dial"""

    start: float  # degree, clockwise from 12 o'clock
    end: float
    inner: float  # distances from the center, relative to the inner radius
    outer: float
    color: str
    name: str


@dataclass
class Hand:
    """a moving hand, the shape of the hands in the .slint files"""

    tip: float  # relative to the inner radius
    shoulder: float
    tail: float
    half_width: float  # px


@dataclass
class Card:
    """a card that turns as a whole (heading indicator): its paths are redrawn every frame"""

    ticks: list  # Tick at their angle on the card
    paths: int  # number of paths the ticks are split into (each rebuilds its elements per frame)
    labels: list  # (angle, text) on the card, the text stays upright
    label_radius: float  # relative to the inner radius


@dataclass
class Shape:
    """a static filled shape, polygons in units of the inner radius from the center (y down)"""

    name: str
    color: str
    polygons: list
    # drawn over the turning card on purpose (redrawn with it), not checked for overlap
    over_card: bool = False


@dataclass
class Rotor:
    """a shape that turns around the center by up to +-max_angle (the aircraft symbol of the
    turn coordinator), polygons in units of the inner radius from the center (y down)"""

    name: str
    color: str
    polygons: list
    max_angle: float  # degree
    sin_name: str  # properties with the sine and cosine of the angle in the .slint file
    cos_name: str


@dataclass
class Dial:
    file: str
    min_distance: float  # smallest distance of a static box from the center, rel. inner radius
    hands: list
    ticks: list = field(default_factory=list)
    arcs: list = field(default_factory=list)
    # ticks drawn after the normal ticks (for example a red line), each in its own path
    marks: list = field(default_factory=list)
    # groups of ticks chosen by hand instead of the grouping by distance
    groups: list = None
    card: Card = None
    shapes: list = field(default_factory=list)
    rotor: Rotor = None
    # boxes of hand-written static elements (Rectangle, Text), in units of the inner radius
    # from the center (x0, y0, x1, y1), checked against the rotor
    statics: list = field(default_factory=list)


def ratio(r):
    """distance relative to the inner radius -> relative to the instrument size"""
    return (0.5 - RING_RATIO) * r


def tick_coefficients(tick, corner, axis):
    """A and B of the coordinate `size_float * A + B` of a tick corner"""
    along, side = corner
    a = math.radians(tick.angle)
    r = ratio(tick.outer if along == "outer" else tick.inner)
    half_width = tick.half_width * side
    if axis == "x":
        return 0.5 + r * math.sin(a), half_width * math.cos(a)
    return 0.5 - r * math.cos(a), half_width * math.sin(a)


def arc_point(angle, r):
    """A of x and y of a point on an arc (B is 0)"""
    a = math.radians(angle)
    return 0.5 + ratio(r) * math.sin(a), 0.5 - ratio(r) * math.cos(a)


def tick_extremes(group):
    """(A, B) of the smallest and largest x and y of a group of ticks"""
    corners = [(t, c) for t in group for c in TICK_CORNERS]

    def value(e, axis):
        a, b = tick_coefficients(*e, axis)
        return a * SIZE + b

    x0 = min(corners, key=lambda e: value(e, "x"))
    x1 = max(corners, key=lambda e: value(e, "x"))
    y0 = min(corners, key=lambda e: value(e, "y"))
    y1 = max(corners, key=lambda e: value(e, "y"))
    return (
        tick_coefficients(*x0, "x"),
        tick_coefficients(*y0, "y"),
        tick_coefficients(*x1, "x"),
        tick_coefficients(*y1, "y"),
    )


def arc_extremes(arc, start, end):
    """(A, 0) of the smallest and largest x and y of a piece of an arc"""
    angles = [start, end] + [a for a in range(0, 721, 90) if start < a < end]
    points = [arc_point(a, r) for a in angles for r in (arc.inner, arc.outer)]
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return (min(xs), 0), (min(ys), 0), (max(xs), 0), (max(ys), 0)


def box(extremes):
    """box in px at SIZE, with the 1 unit margin of the viewbox"""
    (ax0, bx0), (ay0, by0), (ax1, bx1), (ay1, by1) = extremes
    return (
        ax0 * SIZE + bx0 - 1,
        ay0 * SIZE + by0 - 1,
        ax1 * SIZE + bx1 + 1,
        ay1 * SIZE + by1 + 1,
    )


def distance(b):
    """distance of the box from the center"""
    dx = max(b[0] - CENTER, 0, CENTER - b[2])
    dy = max(b[1] - CENTER, 0, CENTER - b[3])
    return math.hypot(dx, dy)


def group_ticks(ticks, min_distance):
    """fewest groups of neighbouring ticks whose boxes keep the distance"""
    best = None
    for start in range(len(ticks)):
        result, current = [], []
        for i in range(len(ticks)):
            index = (start + i) % len(ticks)
            candidate = [ticks[k] for k in current + [index]]
            if current and distance(box(tick_extremes(candidate))) < min_distance:
                result.append(current)
                current = [index]
            else:
                current.append(index)
        result.append(current)
        if best is None or len(result) < len(best):
            best = result
    return [[ticks[k] for k in g] for g in sorted(best, key=lambda g: g[0])]


def cut_arc(arc, min_distance):
    """fewest pieces whose boxes keep the distance

    A shorter piece has a smaller box, so making each piece as long as possible (in steps of
    0.25 degree) gives the fewest pieces. Near 12, 3, 6 and 9 o'clock pieces can be much longer
    than near the diagonals.
    """
    pieces = []
    start = arc.start
    while start < arc.end:
        end = start
        while end < arc.end and distance(box(arc_extremes(arc, start, min(end + 0.25, arc.end)))) >= min_distance:
            end = min(end + 0.25, arc.end)
        if end == start:
            sys.exit(f"{arc.name}: no cut found at {start} degree")
        pieces.append((start, end))
        start = end
    return pieces


def hand_box(hand, angle):
    s, c = math.sin(angle), math.cos(angle)
    points = [
        (-hand.tail, -hand.half_width),
        (hand.shoulder, -hand.half_width),
        (hand.tip, 0),
        (hand.shoulder, hand.half_width),
        (-hand.tail, hand.half_width),
    ]
    xs, ys = [], []
    for along, across in points:
        along = along * INNER_RADIUS if along != 0 else 0
        xs.append(CENTER + along * s + across * c)
        ys.append(CENTER - along * c + across * s)
    return min(xs) - 1, min(ys) - 1, max(xs) + 1, max(ys) + 1


def overlap(a, b):
    return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


def expression(a, b):
    # without a dependency on the size the property is a constant and needs no binding
    if abs(a) < 5e-7:
        return f"{b:.4f}"
    if abs(b) < 5e-5:
        return f"size_float * {a:.6f}"
    return f"size_float * {a:.6f} {'+' if b > 0 else '-'} {abs(b):.4f}"


def viewbox_lines(extremes):
    (ax0, bx0), (ay0, by0), (ax1, bx1), (ay1, by1) = extremes
    return [
        f"        viewbox-x: {expression(ax0, bx0 - 1)};",
        f"        viewbox-y: {expression(ay0, by0 - 1)};",
        f"        viewbox-width: {expression(ax1 - ax0, bx1 - bx0 + 2)};",
        f"        viewbox-height: {expression(ay1 - ay0, by1 - by0 + 2)};",
        "        x: self.viewbox-x * 1px;",
        "        y: self.viewbox-y * 1px;",
        "        width: self.viewbox-width * 1px;",
        "        height: self.viewbox-height * 1px;",
    ]


def tick_path(group):
    out = [f"    // {', '.join(f'{t.angle:g}deg' for t in group)}", "    Path {"]
    out += viewbox_lines(tick_extremes(group))
    out.append(f"        fill: {group[0].color};")
    for tick in group:
        for i, corner in enumerate(TICK_CORNERS):
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            out.append(f"            x: {expression(*tick_coefficients(tick, corner, 'x'))};")
            out.append(f"            y: {expression(*tick_coefficients(tick, corner, 'y'))};")
            out.append("        }")
        out.append("")
        out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def card_tick_path(group, card_box):
    first, last = group[0].angle, group[-1].angle
    out = [f"    // card ticks {first:g}deg to {last:g}deg, they turn with the card", "    Path {"]
    out += viewbox_lines(card_box)
    out.append(f"        fill: {group[0].color};")
    for tick in group:
        for i, corner in enumerate(TICK_CORNERS):
            # offset from the center on the card before it is turned
            ax, bx = tick_coefficients(tick, corner, "x")
            ay, by = tick_coefficients(tick, corner, "y")
            px, py = expression(ax - 0.5, bx), expression(ay - 0.5, by)
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            # written out instead of calling card_x/card_y: the compiler then reads each
            # property once per path; in a function it reads them (and computes their sine and
            # cosine) again for every call, and each read costs a dependency node of heap
            out.append(f"            x: center + ({px}) * cos_heading + ({py}) * sin_heading;")
            out.append(f"            y: center - ({px}) * sin_heading + ({py}) * cos_heading;")
            out.append("        }")
        out.append("")
        out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def card_label(angle, text, radius):
    a = math.radians(angle)
    px = expression(ratio(radius) * math.sin(a), 0)
    py = expression(-ratio(radius) * math.cos(a), 0)
    return [
        f"    // {angle:g}deg",
        "    Text {",
        f"        x: (center + ({px}) * cos_heading + ({py}) * sin_heading - label_half_width) * 1px;",
        f"        y: (center - ({px}) * sin_heading + ({py}) * cos_heading - label_half_height) * 1px;",
        "        width: 2px * label_half_width;",
        "        height: 2px * label_half_height;",
        f'        text: "{text}";',
        "        color: Theme.marking;",
        "        font-size: 14px;",
        "        horizontal-alignment: TextHorizontalAlignment.center;",
        "        vertical-alignment: TextVerticalAlignment.center;",
        "    }",
        "",
    ]


def shape_points(shape):
    """(A, A) of x and y of all points of a shape"""
    return [
        (0.5 + ratio(x), 0.5 + ratio(y)) for polygon in shape.polygons for x, y in polygon
    ]


def shape_extremes(shape):
    points = shape_points(shape)
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return (min(xs), 0), (min(ys), 0), (max(xs), 0), (max(ys), 0)


def shape_path(shape):
    out = [f"    // {shape.name}", "    Path {"]
    out += viewbox_lines(shape_extremes(shape))
    out.append(f"        fill: {shape.color};")
    for polygon in shape.polygons:
        for i, (x, y) in enumerate(polygon):
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            out.append(f"            x: {expression(0.5 + ratio(x), 0)};")
            out.append(f"            y: {expression(0.5 + ratio(y), 0)};")
            out.append("        }")
        out.append("")
        out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def rotor_half_extents(rotor):
    """half width and half height of a symmetric box around the center that contains the
    shape before it is turned (in units of the inner radius)"""
    points = [p for polygon in rotor.polygons for p in polygon]
    return max(abs(x) for x, _ in points), max(abs(y) for _, y in points)


def rotor_box(rotor, angle):
    """box in px at SIZE of the turned shape, the same formula as in the .slint file, with
    the 1 unit margin of the viewbox"""
    w, h = (INNER_RADIUS * e for e in rotor_half_extents(rotor))
    a = math.radians(angle)
    ex = w * abs(math.cos(a)) + h * abs(math.sin(a))
    ey = w * abs(math.sin(a)) + h * abs(math.cos(a))
    return CENTER - ex - 1, CENTER - ey - 1, CENTER + ex + 1, CENTER + ey + 1


def rotor_path(rotor):
    w, h = rotor_half_extents(rotor)
    wx, hx = expression(ratio(w), 0), expression(ratio(h), 0)
    s, c = rotor.sin_name, rotor.cos_name
    # the box contains the turned box of the shape: half extents w * |cos| + h * |sin| and
    # w * |sin| + h * |cos|, cheaper than the smallest box over all points (fewer reads)
    out = [
        f"    // {rotor.name}, turns with the {s}/{c} angle, its box follows it",
        "    Path {",
        f"        viewbox-x: center - ({wx}) * abs({c}) - ({hx}) * abs({s}) - 1;",
        f"        viewbox-y: center - ({wx}) * abs({s}) - ({hx}) * abs({c}) - 1;",
        f"        viewbox-width: 2 * (({wx}) * abs({c}) + ({hx}) * abs({s})) + 2;",
        f"        viewbox-height: 2 * (({wx}) * abs({s}) + ({hx}) * abs({c})) + 2;",
        "        x: self.viewbox-x * 1px;",
        "        y: self.viewbox-y * 1px;",
        "        width: self.viewbox-width * 1px;",
        "        height: self.viewbox-height * 1px;",
        f"        fill: {rotor.color};",
    ]
    for polygon in rotor.polygons:
        for i, (x, y) in enumerate(polygon):
            px, py = expression(ratio(x), 0), expression(ratio(y), 0)
            # turned clockwise by the angle, written out (see the heading card)
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            out.append(f"            x: center + ({px}) * {c} - ({py}) * {s};")
            out.append(f"            y: center + ({px}) * {s} + ({py}) * {c};")
            out.append("        }")
        out.append("")
        out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def arc_path(arc, start, end):
    out = [f"    // {arc.name}, {start:g}deg to {end:g}deg", "    Path {"]
    out += viewbox_lines(arc_extremes(arc, start, end))
    out.append(f"        fill: {arc.color};")
    # outer edge clockwise, inner edge back
    steps = [
        ("MoveTo", start, arc.outer, None),
        ("ArcTo", end, arc.outer, "true"),
        ("LineTo", end, arc.inner, None),
        ("ArcTo", start, arc.inner, "false"),
    ]
    for element, angle, r, sweep in steps:
        x, y = arc_point(angle, r)
        out.append("")
        out.append(f"        {element} {{")
        out.append(f"            x: {expression(x, 0)};")
        out.append(f"            y: {expression(y, 0)};")
        if sweep:
            out.append(f"            radius-x: {expression(ratio(r), 0)};")
            out.append(f"            radius-y: {expression(ratio(r), 0)};")
            out.append(f"            sweep: {sweep};")
        out.append("        }")
    out.append("")
    out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def generate(dial):
    """the generated lines and a report, exits if a static box can be reached by a hand"""
    min_distance = dial.min_distance * INNER_RADIUS
    if dial.groups:
        tick_groups = dial.groups
    else:
        tick_groups = group_ticks(dial.ticks, min_distance) if dial.ticks else []
    arc_pieces = [(arc, s, e) for arc in dial.arcs for s, e in cut_arc(arc, min_distance)]

    boxes = [box(tick_extremes(g)) for g in tick_groups]
    boxes += [box(arc_extremes(*p)) for p in arc_pieces]
    boxes += [box(tick_extremes([m])) for m in dial.marks]
    for hand in dial.hands:
        for step in range(3600):
            hand_b = hand_box(hand, math.radians(step / 10))
            if any(overlap(hand_b, b) for b in boxes):
                sys.exit(f"{dial.file}: a hand overlaps a static box at {step / 10} degree")

    out = []
    for piece in arc_pieces:
        out += arc_path(*piece)
    for group in tick_groups:
        out += tick_path(group)
    for mark in dial.marks:
        out += tick_path([mark])

    card_report = ""
    if dial.card:
        card = dial.card
        # the box of the whole card, it contains every tick at every heading
        outer = max(t.outer for t in card.ticks)
        half_width = max(t.half_width for t in card.ticks)
        card_box = (
            (0.5 - ratio(outer), -half_width),
            (0.5 - ratio(outer), -half_width),
            (0.5 + ratio(outer), half_width),
            (0.5 + ratio(outer), half_width),
        )
        per_path = math.ceil(len(card.ticks) / card.paths)
        for i in range(0, len(card.ticks), per_path):
            out += card_tick_path(card.ticks[i : i + per_path], card_box)
        for angle, text in card.labels:
            out += card_label(angle, text, card.label_radius)
        # static shapes must stay outside the box of the turning card
        for shape in dial.shapes:
            if not shape.over_card and overlap(box(shape_extremes(shape)), box(card_box)):
                sys.exit(f"{dial.file}: {shape.name} overlaps the box of the card")
        card_report = (
            f", card: {card.paths} tick paths of {per_path} ticks, {len(card.labels)} labels"
        )
    for shape in dial.shapes:
        out += shape_path(shape)

    rotor_report = ""
    if dial.rotor:
        rotor = dial.rotor
        statics = boxes + [box(shape_extremes(sh)) for sh in dial.shapes]
        statics += [
            (CENTER + x0 * INNER_RADIUS, CENTER + y0 * INNER_RADIUS,
             CENTER + x1 * INNER_RADIUS, CENTER + y1 * INNER_RADIUS)
            for x0, y0, x1, y1 in dial.statics
        ]
        steps = int(rotor.max_angle * 10)
        for step in range(-steps, steps + 1):
            if any(overlap(rotor_box(rotor, step / 10), b) for b in statics):
                sys.exit(f"{dial.file}: {rotor.name} overlaps a static box at {step / 10} degree")
        out += rotor_path(rotor)
        rotor_report = f", {rotor.name}: no overlap up to +-{rotor.max_angle:g} degree"

    report = (
        f"{dial.file}: {len(arc_pieces)} arc paths, {len(tick_groups)} tick paths "
        f"{[len(g) for g in tick_groups]}, {len(dial.marks)} marks, "
        + ("no overlap with the hands" if dial.hands else "no hands to check")
        + card_report
        + (f", {len(dial.shapes)} shapes" if dial.shapes else "")
        + rotor_report
    )
    return out, report


def attitude():
    # bank ticks in the ring, from the outer edge (1.25 of the inner radius) to the inner edge
    # the moving inner disc has a fixed box, the hand-chosen groups keep the tick boxes away
    # from it, so there are no hands to check
    def tick(angle, width):
        return Tick(angle, 1.0, 1.25, width / 2, "Theme.marking")

    groups = [
        [tick(0, MARKING_WIDTH)],
        [tick(a, MARKING_WIDTH / 2) for a in (-20, -10, 10, 20)],
        [tick(a, MARKING_WIDTH) for a in (-60, -30)],
        [tick(a, MARKING_WIDTH) for a in (30, 60)],
    ]
    return Dial("ui/attitude.slint", 0, [], groups=groups)


def altimeter():
    # ticks every 20 ft, long and wide ones every 100 ft
    ticks = [
        Tick(
            k * 360 / 50,
            0.85 if k % 5 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if k % 5 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        for k in range(50)
    ]
    # 100 ft hand, the 1000 ft hand is shorter
    hands = [Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8)]
    return Dial("ui/altimeter.slint", 0.79, hands, ticks)


# airspeed scale: 0 to 40 kt on the first 30 degree, then 1.875 degree per kt
# (40 kt at 30 degree, 200 kt at 330 degree), like ui/airspeed.slint
def airspeed_angle(kt):
    return kt * 0.75 if kt < 40 else 30 + (kt - 40) * 1.875


# speed limits of a typical small trainer (Cessna 172), in kt
V_S0 = 40  # stall speed with flaps, start of the white arc
V_FE = 85  # highest speed with flaps, end of the white arc
V_S1 = 48  # stall speed clean, start of the green arc
V_NO = 129  # highest cruising speed, end of the green and start of the yellow arc
V_NE = 163  # never exceed, red line


def airspeed():
    # ticks every 5 kt from 40 to 200 kt, long and wide ones every 10 kt
    ticks = [
        Tick(
            airspeed_angle(kt),
            0.85 if kt % 10 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if kt % 10 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        for kt in range(40, 201, 5)
    ]
    # the arcs lie in the ring, inside the digits: white inside, green and yellow outside
    arcs = [
        Arc(airspeed_angle(V_S0), airspeed_angle(V_FE), 1.0, 1.04, "Theme.marking", "white arc"),
        Arc(airspeed_angle(V_S1), airspeed_angle(V_NO), 1.04, 1.10, "Theme.normal", "green arc"),
        Arc(airspeed_angle(V_NO), airspeed_angle(V_NE), 1.04, 1.10, "Theme.caution", "yellow arc"),
    ]
    marks = [Tick(airspeed_angle(V_NE), 0.92, 1.10, MARKING_WIDTH / 2, "Theme.limit")]
    hands = [Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8)]
    return Dial("ui/airspeed.slint", 0.79, hands, ticks, arcs, marks)


# vertical speed scale, like ui/vertical-speed.slint: 0 at 9 o'clock, climb clockwise, descent
# counterclockwise; 0 to 1000 fpm on 90 degree, 1000 to 2000 fpm compressed on 75 degree
def vertical_speed_angle(fpm):
    v = abs(fpm)
    a = v * 0.09 if v <= 1000 else 90 + (v - 1000) * 0.075
    return (270 + a if fpm >= 0 else 270 - a) % 360


def vertical_speed():
    # ticks every 100 fpm from -2000 to 2000 fpm, long and wide ones every 500 fpm
    ticks = [
        Tick(
            vertical_speed_angle(fpm),
            0.85 if fpm % 500 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if fpm % 500 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        # in the order around the dial, so the grouping joins neighbours
        for fpm in range(-2000, 2001, 100)
    ]
    hands = [Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8)]
    return Dial("ui/vertical-speed.slint", 0.79, hands, ticks)


# turn coordinator: a standard rate turn (3 degree per second) banks the aircraft symbol by
# 20 degree, onto the L and R marks; it stops at 6 degree per second (40 degree)
TURN_STANDARD_BANK = 20
TURN_MAX_BANK = 40


def turn_coordinator():
    w = MARKING_WIDTH / 2
    # level marks at 9 and 3 o'clock, standard rate marks 20 degree below them
    marks = [
        Tick(a, 0.85, 1.0, w, "Theme.marking")
        for a in (270, 90, 270 - TURN_STANDARD_BANK, 90 + TURN_STANDARD_BANK)
    ]
    # aircraft seen from behind: wings and a fin on top; the round fuselage is a Rectangle
    # in the .slint file, it doesn't change when turned
    aircraft = [
        [(-0.70, -0.03), (0.70, -0.03), (0.70, 0.03), (-0.70, 0.03)],
        [(-0.025, -0.22), (0.025, -0.22), (0.025, 0.0), (-0.025, 0.0)],
    ]
    rotor = Rotor(
        "aircraft symbol", "Theme.marking", aircraft, TURN_MAX_BANK, "sin_bank", "cos_bank"
    )
    statics = [
        # inclinometer tube with the ball, Rectangles in the .slint file
        (-0.42, 0.66, 0.42, 0.80),
        # "2 MIN" text below it
        (-0.25, 0.81, 0.25, 0.99),
    ]
    return Dial("ui/turn-coordinator.slint", 0, [], marks=marks, rotor=rotor, statics=statics)


def heading():
    # card ticks every 5 degree, long and wide ones every 10 degree
    ticks = [
        Tick(
            a,
            0.85 if a % 10 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if a % 10 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        for a in range(0, 360, 5)
    ]
    names = {0: "N", 90: "E", 180: "S", 270: "W"}
    labels = [(a, names.get(a, str(a // 10))) for a in range(0, 360, 30)]
    # each card path rebuilds its elements every frame: 8 paths of 9 ticks need about 1.3 KB
    # each (one path 10 KB, 4 paths 2.5 KB weren't found any more in the fragmented heap of the
    # host check), and a band of 9 ticks stays within the 512 reserved rasterizer cells
    card = Card(ticks, 8, labels, 0.68)

    # heading mark at the top and marks at 3, 6 and 9 o'clock, in the ring outside the card
    def ring_mark(angle):
        # a narrow quadrilateral in the ring, pointing to the center, from 1.05 to 1.2
        a = math.radians(angle)
        s, c = math.sin(a), math.cos(a)
        w = MARKING_WIDTH / 2 / INNER_RADIUS
        return [
            (r * s + side * w * c, -r * c + side * w * s)
            for r, side in ((1.05, -1), (1.2, -1), (1.2, 1), (1.05, 1))
        ]

    lubber = [(0.0, -1.05), (-0.09, -1.22), (0.09, -1.22)]
    # aircraft seen from above, nose up: fuselage, wings, tail
    aircraft = [
        [(-0.03, -0.38), (0.03, -0.38), (0.03, 0.30), (-0.03, 0.30)],
        [(-0.36, -0.08), (0.36, -0.08), (0.36, 0.0), (-0.36, 0.0)],
        [(-0.14, 0.24), (0.14, 0.24), (0.14, 0.30), (-0.14, 0.30)],
    ]
    shapes = [
        Shape("heading mark at the top, in the ring", "Theme.vehicle", [lubber]),
        # one shape each, a common box would span the card
        *(
            Shape(f"mark at {a}deg, in the ring", "Theme.marking", [ring_mark(a)])
            for a in (90, 180, 270)
        ),
        Shape("aircraft symbol, over the card", "Theme.vehicle", aircraft, over_card=True),
    ]
    return Dial("ui/heading.slint", 0, [], card=card, shapes=shapes)


def main():
    check = "--check" in sys.argv[1:]
    root = Path(__file__).resolve().parent.parent
    outdated = []
    for dial in (
        attitude(),
        altimeter(),
        airspeed(),
        heading(),
        vertical_speed(),
        turn_coordinator(),
    ):
        lines, report = generate(dial)
        print(report, file=sys.stderr)
        path = root / dial.file
        text = path.read_text()
        begin = text.index(BEGIN + "\n") + len(BEGIN) + 1
        end = text.index(END + "\n")
        new = text[:begin] + "\n".join(lines) + "\n" + text[end:]
        if new != text:
            if check:
                outdated.append(dial.file)
            else:
                path.write_text(new)
                print(f"{dial.file} updated", file=sys.stderr)
    if outdated:
        sys.exit(f"not up to date, run tools/dial-paths.py: {', '.join(outdated)}")


if __name__ == "__main__":
    main()
