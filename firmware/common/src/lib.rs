use alloc::boxed::Box;
use alloc::rc::Rc;
use core::time::Duration;

use slint::platform::software_renderer::{
    MinimalSoftwareWindow, RepaintBufferType, Rgb565BigEndianPixel,
};

/// Instruments of ui/basic-panel-device.slint
pub const INSTRUMENTS: i32 = 6;
/// How long each instrument is shown in the automatic sequence
pub const INSTRUMENT_TIME: Duration = Duration::from_secs(20);

/// Slint platform with the single window of the display
struct Platform {
    window: Rc<MinimalSoftwareWindow>,
    // time since the start, from the timer of the HAL
    uptime: fn() -> Duration,
}

impl slint::platform::Platform for Platform {
    fn create_window_adapter(
        &self,
    ) -> Result<Rc<dyn slint::platform::WindowAdapter>, slint::PlatformError> {
        Ok(self.window.clone())
    }

    fn duration_since_start(&self) -> Duration {
        (self.uptime)()
    }
}

/// Creates the window of a display of `width` x `height` pixels and sets the Slint platform with
/// it, `uptime` gives the time since the start
pub fn init_window(
    width: usize,
    height: usize,
    uptime: fn() -> Duration,
) -> Rc<MinimalSoftwareWindow> {
    // ReusedBuffer only redraws what changed, the frame buffer keeps the rest
    // (needs the patched renderer, the original blends Paths outside of the redrawn region,
    // see issues/rp2040)
    let window = MinimalSoftwareWindow::new(RepaintBufferType::ReusedBuffer);
    window.set_size(slint::PhysicalSize::new(width as u32, height as u32));
    slint::platform::set_platform(Box::new(Platform {
        window: window.clone(),
        uptime,
    }))
    .unwrap();
    window
}

/// Renders what changed into the frame buffer of a display `width` pixels wide. Returns the
/// first and last changed row and their pixels in the byte order of the display, None if nothing
/// changed.
pub fn render<'a>(
    window: &MinimalSoftwareWindow,
    frame_buffer: &'a mut [Rgb565BigEndianPixel],
    width: usize,
) -> Option<(u16, u16, &'a [u8])> {
    let mut changed_rows = None;
    window.draw_if_needed(|renderer| {
        let region = renderer.render(frame_buffer, width);
        let (origin, size) = (region.bounding_box_origin(), region.bounding_box_size());
        if size.width > 0 && size.height > 0 {
            changed_rows = Some((origin.y as usize, origin.y as usize + size.height as usize));
        }
    });
    let (first_row, end_row) = changed_rows?;
    let frame_buffer: &'a [Rgb565BigEndianPixel] = frame_buffer;
    // full rows are contiguous in the frame buffer, so they are sent with one transfer
    let rows = &frame_buffer[first_row * width..end_row * width];
    // SAFETY: Rgb565BigEndianPixel is a plain u16 in display byte order
    let rows = unsafe {
        core::slice::from_raw_parts(rows.as_ptr() as *const u8, core::mem::size_of_val(rows))
    };
    Some((first_row as u16, (end_row - 1) as u16, rows))
}

/// Sets the instrument properties of the ui to the values: the `BasicPanelDevice` of each firmware is a
/// type of its own, generated by its build script
#[macro_export]
macro_rules! show {
    ($ui:expr, $values:expr) => {{
        let values: $crate::demo::Values = $values;
        $ui.set_roll(values.roll);
        $ui.set_pitch(values.pitch);
        $ui.set_altitude(values.altitude);
        $ui.set_airspeed(values.airspeed);
        $ui.set_heading(values.heading);
        $ui.set_vertical_speed(values.vertical_speed);
        $ui.set_turn_rate(values.turn_rate);
        $ui.set_slip(values.slip);
    }};
}

/// The instrument after `instrument`
pub fn next_instrument(instrument: i32) -> i32 {
    (instrument + 1) % INSTRUMENTS
}

/// The instrument before `instrument`
pub fn previous_instrument(instrument: i32) -> i32 {
    (instrument + INSTRUMENTS - 1) % INSTRUMENTS
}

/// Automatic sequence of the instruments: the next one every INSTRUMENT_TIME, counted from when
/// the sequence was switched on
#[derive(Default)]
pub struct Sequence {
    // when it was switched on or last showed the next instrument, None while it is off
    since: Option<Duration>,
}

impl Sequence {
    /// Whether the next instrument is due at `now`, `on` while the sequence is switched on
    pub fn next(&mut self, on: bool, now: Duration) -> bool {
        match self.since {
            _ if !on => {
                self.since = None;
                false
            }
            Some(since) if now - since < INSTRUMENT_TIME => false,
            Some(_) => {
                self.since = Some(now);
                true
            }
            None => {
                self.since = Some(now);
                false
            }
        }
    }
}

/// Frames per second and the heap peak, for the status line
pub struct Statistics {
    start: Duration,
    frames: u32,
}

impl Statistics {
    pub fn new(now: Duration) -> Self {
        Self {
            start: now,
            frames: 0,
        }
    }

    /// Counts a frame sent to the display
    pub fn frame(&mut self) {
        self.frames += 1;
    }

    /// The status line once per second while frames are sent, None in between
    pub fn status(&mut self, now: Duration) -> Option<slint::SharedString> {
        let elapsed = now - self.start;
        if elapsed < Duration::from_secs(1) || self.frames == 0 {
            return None;
        }
        let fps = self.frames as f32 * 1000.0 / elapsed.as_millis() as f32;
        self.start = now;
        self.frames = 0;
        Some(slint::format!(
            "{:.1} fps, heap peak {} of {} KB",
            fps,
            heap::peak() / 1024,
            heap::size() / 1024
        ))
    }
}
